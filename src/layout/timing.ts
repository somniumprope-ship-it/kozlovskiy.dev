/**
 * Общий «график» открытия/закрытия проекта на десктопе: левая и правая части идут синхронно.
 * 0 … OUT_END      — работы справа уезжают, слева уезжают секции и сжимается карточка с фото;
 * OUT_END + PAUSE  — пауза, затем справа выезжают фото, а слева — плашка с описанием.
 */
export const OUT_END = 1.1;
export const PAUSE = 0.3;
export const IN_START = OUT_END + PAUSE;
/** Когда начинается сжатие (длится 0.5 с, чтобы закончиться к OUT_END) */
export const COMPACT_AT = OUT_END - 0.5;
